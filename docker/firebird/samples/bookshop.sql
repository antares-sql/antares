         IIF(MOD(:i, 2) = 0, 'Description of volume ' || :i || '. ' || LPAD('', MOD(:i, 5) * 400, 'Lorem ipsum dolor sit amet. '), NULL),
         x'CAFE' || x'BABE',
         DATEADD(:i * 3 HOUR TO TIMESTAMP '2024-01-01 08:30:00.1234')
      );
      i = i + 1;
   END

   -- 300 customers
   i = 1;
   WHILE (i <= 300) DO
   BEGIN
      INSERT INTO CUSTOMERS (NAME, EMAIL, COUNTRY, VIP, REGISTERED_AT, NOTES)
      VALUES (
         'Customer ' || :i || TRIM(TRAILING FROM IIF(MOD(:i, 10) = 0, ' Müller-Ñúñez', '')),
         IIF(MOD(:i, 8) = 0, NULL, 'customer' || :i || '@example.com'),
         DECODE(MOD(:i, 8), 0, 'IT', 1, 'FR', 2, 'DE', 3, 'ES', 4, 'GB', 5, 'US', 6, 'JP', 'BR'),
         MOD(:i, 15) = 0,
         DATEADD(:i * 29 HOUR TO CAST('2023-03-01 10:00:00 Europe/Rome' AS TIMESTAMP WITH TIME ZONE)),
         IIF(MOD(:i, 6) = 0, 'Prefers e-mail; line 1' || ASCII_CHAR(10) || 'line 2', NULL)
      );
      i = i + 1;
   END

   -- 1500 orders with 1 to 4 items
   i = 1;
   WHILE (i <= 1500) DO
   BEGIN
      INSERT INTO ORDERS (CUSTOMER_ID, ORDER_DATE, DELIVERY_TIME, STATUS, PAID, INVOICE_NUMBER, TOTAL)
      VALUES (
         MOD(:i * 7, 300) + 1,
         DATEADD(:i * 311 MINUTE TO TIMESTAMP '2024-01-01 00:00:00'),
         IIF(MOD(:i, 3) = 0, NULL, DATEADD(MOD(:i, 10) HOUR TO TIME '09:00:00')),
         TRIM(DECODE(MOD(:i, 10), 0, 'CANCELLED', 1, 'NEW', 2, 'NEW', 3, 'SHIPPED', 'PAID')),
         MOD(:i, 10) > 2,
         IIF(MOD(:i, 10) > 2, NEXT VALUE FOR SEQ_INVOICE, NULL),
         0
      )
      RETURNING ID INTO :order_id;

      n = MOD(:i, 4) + 1;
      j = 1;
      WHILE (j <= n) DO
      BEGIN
         book_id = MOD(:i * 13 + :j * 101, 400) + 1;
         INSERT INTO ORDER_ITEMS (ORDER_ID, LINE_NO, BOOK_ID, QUANTITY, UNIT_PRICE, DISCOUNT)
         SELECT :order_id, :j, ID, MOD(:i + :j, 3) + 1, PRICE, IIF(MOD(:i, 5) = 0, 0.1, 0)
         FROM BOOKS WHERE ID = :book_id;
         j = j + 1;
      END

      UPDATE ORDERS SET TOTAL = (SELECT COALESCE(SUM(LINE_TOTAL), 0) FROM ORDER_ITEMS WHERE ORDER_ID = :order_id) WHERE ID = :order_id;
      i = i + 1;
   END

   -- Reviews
   i = 1;
   WHILE (i <= 600) DO
   BEGIN
      UPDATE OR INSERT INTO REVIEWS (BOOK_ID, CUSTOMER_ID, RATING, REVIEW_TEXT, REVIEWED_ON)
      VALUES (MOD(:i * 3, 400) + 1, MOD(:i * 11, 300) + 1, MOD(:i, 5) + 1,
         IIF(MOD(:i, 4) = 0, NULL, 'Review #' || :i || ': ' || TRIM(IIF(MOD(:i, 2) = 0, 'great book!', 'not for me, sorry.'))),
         DATEADD(:i DAY TO DATE '2024-02-01'))
      MATCHING (BOOK_ID, CUSTOMER_ID);
      i = i + 1;
   END
END^

