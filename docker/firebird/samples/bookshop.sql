-- Bookshop: Firebird sample database for development (npm run test:db:samples)
-- Covers domains, sequences, exceptions, identity and computed columns, most data types, composite keys,
-- descending/expression/partial indexes, a global temporary table, nested views, selectable and executable
-- procedures, triggers and some thousands of rows.
-- Requires Firebird 5 (partial indexes). The database is created by scripts/sampleDatabases.js.

-- Domains
CREATE DOMAIN D_EMAIL AS VARCHAR(120) CHARACTER SET UTF8 CHECK (VALUE IS NULL OR VALUE LIKE '%_@_%._%');
CREATE DOMAIN D_MONEY AS NUMERIC(12, 2) DEFAULT 0 NOT NULL CHECK (VALUE >= 0);
CREATE DOMAIN D_RATING AS SMALLINT CHECK (VALUE BETWEEN 1 AND 5);
CREATE DOMAIN D_NAME AS VARCHAR(100) CHARACTER SET UTF8 COLLATE UNICODE_CI;

-- Sequences and exceptions
CREATE SEQUENCE SEQ_INVOICE START WITH 1000 INCREMENT BY 1;
CREATE SEQUENCE SEQ_LOG;
CREATE EXCEPTION E_OUT_OF_STOCK 'Not enough copies in stock';
CREATE EXCEPTION E_INVALID_QUANTITY 'The quantity must be positive';

-- Tables
CREATE TABLE COUNTRIES (
   CODE CHAR(2) NOT NULL PRIMARY KEY,
   NAME D_NAME NOT NULL,
   VAT_RATE NUMERIC(5, 2) DEFAULT 22 NOT NULL
);
COMMENT ON TABLE COUNTRIES IS 'ISO 3166 countries with their VAT rate';

CREATE TABLE AUTHORS (
   ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   FIRST_NAME D_NAME,
   LAST_NAME D_NAME NOT NULL,
   BIRTH_DATE DATE,
   COUNTRY CHAR(2) REFERENCES COUNTRIES (CODE),
   BIOGRAPHY BLOB SUB_TYPE TEXT CHARACTER SET UTF8,
   FULL_NAME COMPUTED BY (TRIM(COALESCE(FIRST_NAME || ' ', '') || LAST_NAME))
);

CREATE TABLE PUBLISHERS (
   ID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
   NAME D_NAME NOT NULL UNIQUE,
   WEBSITE VARCHAR(200),
   FOUNDED SMALLINT
);

CREATE TABLE BOOKS (
   ID INTEGER GENERATED BY DEFAULT AS IDENTITY,
   ISBN BIGINT NOT NULL,
   TITLE VARCHAR(200) CHARACTER SET UTF8 NOT NULL,
   AUTHOR_ID INTEGER NOT NULL,
   PUBLISHER_ID INTEGER,
   PUBLISHED DATE,
   PAGES SMALLINT,
   PRICE D_MONEY,
   STOCK INTEGER DEFAULT 0 NOT NULL,
   RATING D_RATING,
   WEIGHT_KG DECFLOAT(16),
   SERIAL_NUMBER INT128,
   AVAILABLE BOOLEAN DEFAULT TRUE NOT NULL,
   COVER BLOB SUB_TYPE BINARY,
   DESCRIPTION BLOB SUB_TYPE TEXT CHARACTER SET UTF8,
   CHECKSUM CHAR(4) CHARACTER SET OCTETS,
   CREATED_AT TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
   PRICE_WITH_VAT COMPUTED BY (PRICE * 1.22),
   CONSTRAINT PK_BOOKS PRIMARY KEY (ID),
   CONSTRAINT UQ_BOOKS_ISBN UNIQUE (ISBN),
   CONSTRAINT FK_BOOKS_AUTHOR FOREIGN KEY (AUTHOR_ID) REFERENCES AUTHORS (ID),
   CONSTRAINT FK_BOOKS_PUBLISHER FOREIGN KEY (PUBLISHER_ID) REFERENCES PUBLISHERS (ID) ON DELETE SET NULL,
   CONSTRAINT CK_BOOKS_PAGES CHECK (PAGES IS NULL OR PAGES > 0)
);
COMMENT ON TABLE BOOKS IS 'Catalog of the books on sale';
COMMENT ON COLUMN BOOKS.STOCK IS 'Copies in the warehouse';

CREATE TABLE CUSTOMERS (
   ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   NAME D_NAME NOT NULL,
   EMAIL D_EMAIL,
   COUNTRY CHAR(2) NOT NULL REFERENCES COUNTRIES (CODE),
   VIP BOOLEAN DEFAULT FALSE NOT NULL,
   REGISTERED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
   NOTES VARCHAR(500)
);

CREATE TABLE ORDERS (
   ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   CUSTOMER_ID INTEGER NOT NULL REFERENCES CUSTOMERS (ID) ON DELETE CASCADE,
   ORDER_DATE TIMESTAMP NOT NULL,
   DELIVERY_TIME TIME,
   STATUS VARCHAR(10) DEFAULT 'NEW' NOT NULL CHECK (STATUS IN ('NEW', 'PAID', 'SHIPPED', 'CANCELLED')),
   PAID BOOLEAN DEFAULT FALSE NOT NULL,
   INVOICE_NUMBER BIGINT,
   TOTAL D_MONEY
);

CREATE TABLE ORDER_ITEMS (
   ORDER_ID INTEGER NOT NULL,
   LINE_NO SMALLINT NOT NULL,
   BOOK_ID INTEGER NOT NULL REFERENCES BOOKS (ID),
   QUANTITY INTEGER NOT NULL,
   UNIT_PRICE NUMERIC(12, 2) NOT NULL,
   DISCOUNT DOUBLE PRECISION DEFAULT 0,
   LINE_TOTAL COMPUTED BY (CAST(QUANTITY * UNIT_PRICE * (1 - DISCOUNT) AS NUMERIC(14, 2))),
   CONSTRAINT PK_ORDER_ITEMS PRIMARY KEY (ORDER_ID, LINE_NO),
   CONSTRAINT FK_ITEMS_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS (ID) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE REVIEWS (
   BOOK_ID INTEGER NOT NULL,
   CUSTOMER_ID INTEGER NOT NULL,
   RATING D_RATING NOT NULL,
   REVIEW_TEXT BLOB SUB_TYPE TEXT CHARACTER SET UTF8,
   REVIEWED_ON DATE DEFAULT CURRENT_DATE NOT NULL,
   PRIMARY KEY (BOOK_ID, CUSTOMER_ID),
   FOREIGN KEY (BOOK_ID) REFERENCES BOOKS (ID) ON DELETE CASCADE,
   FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS (ID) ON DELETE CASCADE
);

CREATE TABLE PRICE_HISTORY (
   ID BIGINT NOT NULL PRIMARY KEY,
   BOOK_ID INTEGER NOT NULL REFERENCES BOOKS (ID) ON DELETE CASCADE,
   OLD_PRICE NUMERIC(12, 2),
   NEW_PRICE NUMERIC(12, 2),
   CHANGED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE GLOBAL TEMPORARY TABLE TMP_CART (
   BOOK_ID INTEGER NOT NULL,
   QUANTITY INTEGER NOT NULL
) ON COMMIT DELETE ROWS;

-- Indexes
CREATE INDEX IX_BOOKS_TITLE ON BOOKS (TITLE);
CREATE DESCENDING INDEX IX_BOOKS_PUBLISHED ON BOOKS (PUBLISHED);
CREATE INDEX IX_AUTHORS_UPPER_NAME ON AUTHORS COMPUTED BY (UPPER(LAST_NAME));
CREATE INDEX IX_ORDERS_DATE ON ORDERS (ORDER_DATE);
CREATE INDEX IX_ORDERS_UNPAID ON ORDERS (CUSTOMER_ID) WHERE PAID = FALSE;
CREATE UNIQUE INDEX UX_CUSTOMERS_EMAIL ON CUSTOMERS (EMAIL);

-- Views
CREATE VIEW V_BOOK_SALES (BOOK_ID, TITLE, COPIES_SOLD, REVENUE) AS
SELECT b.ID, b.TITLE, COALESCE(SUM(i.QUANTITY), 0), COALESCE(SUM(i.LINE_TOTAL), 0)
FROM BOOKS b
LEFT JOIN ORDER_ITEMS i ON i.BOOK_ID = b.ID
LEFT JOIN ORDERS o ON o.ID = i.ORDER_ID AND o.STATUS <> 'CANCELLED'
GROUP BY b.ID, b.TITLE;

CREATE VIEW V_BESTSELLERS AS
SELECT FIRST 20 s.BOOK_ID, s.TITLE, s.COPIES_SOLD, s.REVENUE
FROM V_BOOK_SALES s
ORDER BY s.COPIES_SOLD DESC;

CREATE VIEW V_CUSTOMER_TOTALS (CUSTOMER_ID, NAME, COUNTRY, ORDERS_COUNT, SPENT) AS
SELECT c.ID, c.NAME, c.COUNTRY, COUNT(o.ID), COALESCE(SUM(o.TOTAL), 0)
FROM CUSTOMERS c
LEFT JOIN ORDERS o ON o.CUSTOMER_ID = c.ID AND o.PAID
GROUP BY c.ID, c.NAME, c.COUNTRY;

SET TERM ^ ;

-- Triggers
CREATE TRIGGER TR_BOOKS_PRICE FOR BOOKS
ACTIVE AFTER UPDATE POSITION 0
AS
BEGIN
   IF (NEW.PRICE IS DISTINCT FROM OLD.PRICE) THEN
      INSERT INTO PRICE_HISTORY (ID, BOOK_ID, OLD_PRICE, NEW_PRICE)
      VALUES (NEXT VALUE FOR SEQ_LOG, NEW.ID, OLD.PRICE, NEW.PRICE);
END^

CREATE TRIGGER TR_ITEMS_CHECK FOR ORDER_ITEMS
ACTIVE BEFORE INSERT OR UPDATE POSITION 0
AS
BEGIN
   IF (NEW.QUANTITY <= 0) THEN
      EXCEPTION E_INVALID_QUANTITY;
END^

CREATE TRIGGER TR_ORDERS_INVOICE FOR ORDERS
ACTIVE BEFORE UPDATE POSITION 10
AS
BEGIN
   IF (NEW.PAID AND NOT OLD.PAID AND NEW.INVOICE_NUMBER IS NULL) THEN
      NEW.INVOICE_NUMBER = NEXT VALUE FOR SEQ_INVOICE;
END^

CREATE TRIGGER TR_CUSTOMERS_EMAIL FOR CUSTOMERS
INACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
   NEW.EMAIL = LOWER(NEW.EMAIL);
END^

-- Procedures
CREATE PROCEDURE SP_CUSTOMER_ORDERS (CUSTOMER_ID INTEGER)
RETURNS (ORDER_ID INTEGER, ORDER_DATE TIMESTAMP, ITEMS INTEGER, TOTAL NUMERIC(14, 2))
AS
BEGIN
   FOR SELECT o.ID, o.ORDER_DATE, COUNT(i.LINE_NO), COALESCE(SUM(i.LINE_TOTAL), 0)
      FROM ORDERS o
      LEFT JOIN ORDER_ITEMS i ON i.ORDER_ID = o.ID
      WHERE o.CUSTOMER_ID = :CUSTOMER_ID
      GROUP BY o.ID, o.ORDER_DATE
      ORDER BY o.ORDER_DATE
      INTO :ORDER_ID, :ORDER_DATE, :ITEMS, :TOTAL
   DO
      SUSPEND;
END^

CREATE PROCEDURE SP_ADD_TO_ORDER (ORDER_ID INTEGER, BOOK_ID INTEGER, QUANTITY INTEGER = 1)
RETURNS (LINE_NO SMALLINT)
AS
DECLARE AVAILABLE INTEGER;
DECLARE PRICE NUMERIC(12, 2);
BEGIN
   SELECT STOCK, PRICE FROM BOOKS WHERE ID = :BOOK_ID INTO :AVAILABLE, :PRICE;
   IF (AVAILABLE < QUANTITY) THEN
      EXCEPTION E_OUT_OF_STOCK;

   SELECT COALESCE(MAX(LINE_NO), 0) + 1 FROM ORDER_ITEMS WHERE ORDER_ID = :ORDER_ID INTO :LINE_NO;
   INSERT INTO ORDER_ITEMS (ORDER_ID, LINE_NO, BOOK_ID, QUANTITY, UNIT_PRICE)
   VALUES (:ORDER_ID, :LINE_NO, :BOOK_ID, :QUANTITY, :PRICE);
   UPDATE BOOKS SET STOCK = STOCK - :QUANTITY WHERE ID = :BOOK_ID;
   UPDATE ORDERS SET TOTAL = TOTAL + :QUANTITY * :PRICE WHERE ID = :ORDER_ID;
END^

CREATE PROCEDURE SP_TOP_AUTHORS (LIMIT_ROWS INTEGER = 10)
RETURNS (AUTHOR VARCHAR(201) CHARACTER SET UTF8, COPIES_SOLD BIGINT)
AS
BEGIN
   FOR SELECT FIRST (:LIMIT_ROWS) a.FULL_NAME, SUM(s.COPIES_SOLD)
      FROM AUTHORS a
      JOIN BOOKS b ON b.AUTHOR_ID = a.ID
      JOIN V_BOOK_SALES s ON s.BOOK_ID = b.ID
      GROUP BY a.FULL_NAME
      ORDER BY 2 DESC
      INTO :AUTHOR, :COPIES_SOLD
   DO
      SUSPEND;
END^

