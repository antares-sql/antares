import * as antares from 'common/interfaces/antares';
import { vi } from 'vitest';

export interface CapturedQuery {
   sql: string;
   args?: antares.QueryParams;
}

/**
 * Responds to a captured query: return rows to feed back to the client.
 * Defaults to an empty result.
 */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
export type Responder = (sql: string) => Record<string, any>[] | undefined;

/** Collapse whitespace so snapshots are stable and readable */
export const normalizeSql = (sql: string) => sql.replace(/\s+/g, ' ').trim();

/**
 * Replaces `raw()` on a client instance (without connecting) and records every SQL it receives.
 * Used by characterization tests to pin down the SQL generated by the current clients.
 */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
export function captureRaw (client: { raw: (...args: any[]) => any }, responder?: Responder) {
   const queries: CapturedQuery[] = [];

   vi.spyOn(client, 'raw').mockImplementation(async (sql: string, args?: antares.QueryParams) => {
      queries.push({ sql: normalizeSql(sql), ...(args ? { args } : {}) });
      const rows = responder?.(sql) ?? [];
      return { rows, report: null, fields: [], keys: [], duration: 0 };
   });

   return {
      queries,
      /** Normalized SQL strings only */
      get sql () {
         return queries.map(q => q.sql);
      },
      reset () {
         queries.length = 0;
      }
   };
}
