/**
 * Extracts the word lists (keywords, functions, types, constants) of Ace's SQL
 * modes into src/renderer/libs/editor/sql/aceSqlWords.ts, so the CodeMirror
 * dialects highlight and autocomplete at least the words Ace did.
 *
 * Usage: node scripts/extractAceSqlWords.js (needs ace-builds in node_modules)
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const modes = {
   mysql: 'MysqlHighlightRules',
   pgsql: 'PgsqlHighlightRules',
   sql: 'SqlHighlightRules'
};

/** Ace token type → word category */
const categories = {
   keyword: 'keywords',
   'support.function': 'functions',
   'storage.type': 'types',
   'constant.language': 'constants',
   constant: 'constants'
};

const noop = () => noopProxy;
const noopProxy = new Proxy(noop, {
   get: (_t, prop) => prop === Symbol.toPrimitive ? () => '' : noopProxy,
   apply: () => noopProxy,
   construct: () => noopProxy
});

const extract = (mode, className) => {
   const file = path.join(__dirname, '..', 'node_modules', 'ace-builds', 'src-noconflict', `mode-${mode}.js`);
   const source = fs.readFileSync(file, 'utf8');
   const start = source.indexOf(`ace.define("ace/mode/${mode}_highlight_rules"`);
   const end = source.indexOf('ace.define(', start + 10);
   const moduleSource = source.slice(start, end);

   let mapper = null;
   function TextHighlightRules () {
      // Base class stub: the mode only calls methods of its prototype
   }
   TextHighlightRules.prototype = new Proxy({
      createKeywordMapper (map) {
         mapper = map;
         return noop;
      }
   }, { get: (target, prop) => prop in target ? target[prop] : noop });

   const stubs = {
      '../lib/oop': {
         inherits: (ctor, base) => {
            ctor.prototype = Object.create(base.prototype);
         }
      },
      '../lib/lang': { arrayToMap: () => ({}), escapeRegExp: s => s },
      './text_highlight_rules': { TextHighlightRules }
   };
   const exports = {};
   const ace = {
      define: (_id, _deps, factory) => factory(dep => stubs[dep] ?? new Proxy({}, {
         get: () => TextHighlightRules
      }), exports, { exports })
   };
   vm.runInNewContext(moduleSource, { ace });
   try {
      // eslint-disable-next-line no-new
      new exports[className]();
   }
   catch (err) {
      // The rest of the constructor (token rules) needs Ace modules that aren't stubbed:
      // only the keyword mapper, built first, is needed
      if (!mapper) throw err;
   }

   const words = { keywords: [], functions: [], types: [], constants: [] };
   for (const [token, list] of Object.entries(mapper)) {
      const category = categories[token];
      if (!category) continue;
      words[category].push(...list.split('|').map(w => w.trim().toLowerCase()).filter(w => /^[a-z_][a-z0-9_$]*$/.test(w)));
   }
   for (const key of Object.keys(words))
      words[key] = [...new Set(words[key])].sort().join(' ');
   return words;
};

const result = {};
for (const [mode, className] of Object.entries(modes))
   result[mode] = extract(mode, className);

const out = path.join(__dirname, '..', 'src', 'renderer', 'libs', 'editor', 'sql', 'aceSqlWords.ts');
fs.mkdirSync(path.dirname(out), { recursive: true });
const body = JSON.stringify(result, null, 3)
   .replace(/"([a-zA-Z_][a-zA-Z0-9_]*)":/g, '$1:')
   .replace(/"/g, '\'');
fs.writeFileSync(out, `/* eslint-disable */
// Generated by scripts/extractAceSqlWords.js from the Ace SQL modes: do not edit by hand.
// Space separated word lists, like the ones of @codemirror/lang-sql dialects.

export interface SqlWordLists {
   keywords: string;
   functions: string;
   types: string;
   constants: string;
}

export const aceSqlWords: Record<'mysql' | 'pgsql' | 'sql', SqlWordLists> = ${body};
`);

for (const [mode, words] of Object.entries(result))
   console.log(mode, Object.fromEntries(Object.entries(words).map(([k, v]) => [k, v ? v.split(' ').length : 0])));
