#!/usr/bin/env node
/**
 * Exports the Antares icon set (src/renderer/libs/icons, the single source of truth) as JSON,
 * for the web theme editor (antares-website, /theme-editor), which draws the same icons in its mock of the app.
 *
 *   node scripts/iconKit.js <output file>
 *
 * The file holds the glyphs, the badges, the brand logos and the cut-out sizes: the consumer renders
 * `glyph`, `glyph+badge`, `glyph+off` and `brand:name` like src/renderer/libs/icons/index.ts.
 */
const fs = require('fs');
const path = require('path');

const jiti = require('jiti')(__filename);

const [outFile] = process.argv.slice(2);
if (!outFile) {
   console.error('Usage: node scripts/iconKit.js <output file>');
   process.exit(1);
}

const { glyphs, badges, brands, CUT_STROKE, OFF_CUT_STROKE, OFF_SLASH } = jiti('../src/renderer/libs/icons/index.ts');

const data = {
   $comment: 'Generated by antares/scripts/iconKit.js from src/renderer/libs/icons: do not edit by hand',
   cutStroke: CUT_STROKE,
   offCutStroke: OFF_CUT_STROKE,
   offSlash: OFF_SLASH,
   glyphs,
   badges,
   brands
};

fs.mkdirSync(path.dirname(path.resolve(outFile)), { recursive: true });
fs.writeFileSync(outFile, JSON.stringify(data, null, 2) + '\n');
console.log(`${Object.keys(glyphs).length} glyphs, ${Object.keys(badges).length} badges, ${Object.keys(brands).length} brands -> ${outFile}`);
